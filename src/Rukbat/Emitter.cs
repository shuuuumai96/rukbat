using System.Globalization;
using System.Text;

namespace Rukbat;

internal sealed partial class Emitter(TypeChecker checker)
{
    private const int IndentationWidth = 4;
    private const int RuntimeFailureExitCode = 1;

    private readonly StringBuilder output = new();
    private Module module = null!;
    private string? sourceDirectory;
    private string SourceName(Module current) => sourceDirectory is null || !Path.IsPathFullyQualified(current.Source.Path)
        ? current.Source.Path
        : Path.GetRelativePath(sourceDirectory, current.Source.Path).Replace('\\', '/');
    private int indentation;
    private int temporaryId;
    private ValueType currentReturnType = ValueType.Void;
    private static string Quote(string value) => "'" + value.Replace("'", "''") + "'";
    private static string TypeName(ValueType type)
    {
        if (type.IsNullable)
        {
            return "object";
        }
        if (type.Element is not null)
        {
            return "System.Collections.Generic.List[object]";
        }

        if (type == ValueType.Float)
        {
            return "double";
        }
        return type.Struct is null ? type.Name : "hashtable";
    }

    private void Line(string text) => output.Append(' ', indentation * IndentationWidth).AppendLine(text);

    public string Emit(List<Module> modules)
    {
        sourceDirectory = Path.IsPathFullyQualified(modules[^1].Source.Path)
            ? Path.GetDirectoryName(modules[^1].Source.Path) : null;
        Line("# Generated by Rukbat. Compatible with Windows PowerShell 5.1.");
        Line("& {");
        indentation++;
        Line("param([string[]]$__rukbat_arguments, [string]$__rukbat_working_dir, [string]$__rukbat_script_dir)");
        Line("$ErrorActionPreference = 'Stop'");
        Line("[Console]::OutputEncoding = [System.Text.Encoding]::UTF8");
        Line("Set-StrictMode -Version Latest");
        Line("$__rukbat_modules = @{}");
        EmitErrorRuntime();
        EmitRuntime();
        Line("$__rukbat_arguments = & $__rukbat_array $__rukbat_arguments");
        Line("$__rukbat_json_decode = $null");
        Line("$__rukbat_json_encode = $null");
        Line("$__rukbat_standard = $null");
        if (modules.Any(current => current.StandardName == "json"))
        {
            EmitJsonRuntime();
        }
        var standardModules = modules
            .Where(current => current.StandardName is "files" or "directories" or "path" or "env" or "process" or "text")
            .Select(current => current.StandardName!)
            .ToHashSet(StringComparer.Ordinal);
        if (standardModules.Count != 0)
        {
            EmitStandardRuntime(standardModules);
        }
        Line("try {");
        indentation++;
        foreach (var current in modules)
        {
            EmitModule(current);
        }
        indentation--;
        Line("} catch {");
        indentation++;
        Line($"$__rukbat_failure = & $__rukbat_error $_ {Quote(SourceName(modules[^1]) + ":1")}");
        Line("[Console]::Error.WriteLine(('{0}: error: {1}' -f $__rukbat_failure.__rukbat_location, $__rukbat_failure.message))");
        Line($"exit {RuntimeFailureExitCode}");
        indentation--;
        Line("}");
        indentation--;
        Line("} ([string[]]$args) $PWD.ProviderPath $PSScriptRoot");
        return output.ToString();
    }

    private void EmitModule(Module current)
    {
        module = current;
        Line($"$__rukbat_modules[{Quote(current.Id)}] = New-Module -AsCustomObject " +
            "-ArgumentList $__rukbat_modules, $__rukbat_runtime, $__rukbat_array, $__rukbat_clone, $__rukbat_append, $__rukbat_index, $__rukbat_float, $__rukbat_json_decode, $__rukbat_json_encode, $__rukbat_standard, $__rukbat_error, $__rukbat_raise, $__rukbat_arguments -ScriptBlock {");
        indentation++;
        Line("param($__rukbat_dependencies, $__rukbat_runtime, $__rukbat_array, $__rukbat_clone, $__rukbat_append, $__rukbat_index, $__rukbat_float, $__rukbat_json_decode, $__rukbat_json_encode, $__rukbat_standard, $__rukbat_error, $__rukbat_raise, [System.Collections.Generic.List[object]]$__rukbat_arguments)");
        Line("Set-StrictMode -Version Latest");
        Line("$ErrorActionPreference = 'Stop'");

        // Define functions before top-level execution so calls do not depend on declaration order.
        var functions = checker.Functions.Values.Where(function => function.Module == current).ToArray();
        foreach (var function in functions)
        {
            EmitFunction(function.Function);
        }

        var statements = current.Statements
            .Where(statement => statement is not Function and not StructDeclaration)
            .ToList();
        EmitGuardedStatements(statements, Quote(SourceName(current) + ":1"));

        var exports = functions.Select(function => Quote(function.PowerShellName));
        Line($"Export-ModuleMember -Function @({string.Join(", ", exports)})");
        indentation--;
        Line("}");
    }

    private void EmitFunction(Function function)
    {
        Line($"function {checker.Functions[function].PowerShellName} {{");
        indentation++;
        var parameters = function.Parameters.Select(parameter =>
            $"[{TypeName(checker.Variables[parameter].Type)}]{checker.Variables[parameter].PowerShellName}");
        if (checker.Functions[function].Owner is not null)
        {
            parameters = parameters.Prepend("[hashtable]$__rukbat_self");
        }

        Line($"param({string.Join(", ", parameters)})");
        var previousReturnType = currentReturnType;
        currentReturnType = checker.Functions[function].ReturnType;
        EmitGuardedStatements(function.Body, Location(function));
        currentReturnType = previousReturnType;
        indentation--;
        Line("}");
    }

    private void EmitStatements(List<Statement> statements)
    {
        foreach (var statement in statements)
        {
            if (statement is Import)
            {
                continue;
            }
            // A function has its own location variable, so calls cannot overwrite their caller's location.
            Line($"$__rukbat_location = {Location(statement)}");
            switch (statement)
            {
                case Variable variable:
                    var symbol = checker.Variables[variable];
                    Line($"[{TypeName(symbol.Type)}]{symbol.PowerShellName} = {Expr(variable.Value)}");
                    break;
                case Assignment assignment:
                    Line($"{checker.Variables[assignment].PowerShellName} = {Expr(assignment.Value)}");
                    break;
                case FieldAssignment assignment:
                    Line($"{Address(assignment.Target)} = {Expr(assignment.Value)}");
                    break;
                case IndexAssignment assignment:
                    Line($"{Address(assignment.Target)} = {Expr(assignment.Value)}");
                    break;
                case Return result:
                    EmitReturn(result);
                    break;
                case Throw failure:
                    Line($"& $script:__rukbat_raise ({Expr(failure.Value)}) {Location(failure)}");
                    break;
                case TryCatch guarded:
                    Line("try {");
                    indentation++;
                    EmitStatements(guarded.Body);
                    indentation--;
                    Line("} catch {");
                    indentation++;
                    Line($"[hashtable]{checker.Variables[guarded.Handler].PowerShellName} = & $script:__rukbat_error $_ $__rukbat_location");
                    EmitStatements(guarded.Handler.Body);
                    indentation--;
                    Line("}");
                    break;
                case For loop:
                    var item = "$__rukbat_item" + temporaryId++;
                    Line($"foreach ({item} in {Expr(loop.Items)}) {{");
                    indentation++;
                    var loopVariable = checker.Variables[loop];
                    Line($"[{TypeName(loopVariable.Type)}]{loopVariable.PowerShellName} = {Clone(item, loopVariable.Type)}");
                    EmitStatements(loop.Body);
                    indentation--;
                    Line("}");
                    break;
                case While loop:
                    Line($"while ({Expr(loop.Condition)}) {{");
                    indentation++;
                    EmitStatements(loop.Body);
                    indentation--;
                    Line("}");
                    break;
                case LoopControl control:
                    Line(control.Token.Text);
                    break;
                case ExpressionStatement expression:
                    // Suppress unused values to prevent PowerShell's implicit function output.
                    Line($"$null = {Expr(expression.Value)}");
                    break;
                case Conditional conditional:
                    Line($"if ({Expr(conditional.Condition)}) {{");
                    indentation++;
                    EmitStatements(conditional.Then);
                    indentation--;
                    Line("}");
                    if (conditional.Else.Count != 0)
                    {
                        Line("else {");
                        indentation++;
                        EmitStatements(conditional.Else);
                        indentation--;
                        Line("}");
                    }
                    break;
            }
        }
    }

    private void EmitReturn(Return result)
    {
        if (result.Value is null)
        {
            Line("return");
            return;
        }

        // Unary comma returns an array as one value instead of letting PowerShell enumerate it.
        var value = Expr(result.Value);
        if (currentReturnType.IsNullable && currentReturnType.NonNullable.Element is not null)
        {
            var temporary = $"$__rukbat_return{temporaryId++}";
            Line($"{temporary} = {value}");
            Line($"if ($null -eq {temporary}) {{ return $null }}");
            Line($"return ,({temporary})");
        }
        else
        {
            Line(currentReturnType.Element is not null ? $"return ,({value})" : $"return {value}");
        }
    }

    private string Expr(Expression expression)
    {
        // Ordinary expressions copy values; assignment targets and self use RawExpr or Address.
        var value = RawExpr(expression);
        var actual = checker.Types[expression];
        value = Clone(value, actual);
        return checker.Conversions.TryGetValue(expression, out var expected)
            ? Convert(value, actual, expected)
            : value;
    }

    private static string Convert(string value, ValueType actual, ValueType expected)
    {
        if (expected.NonNullable == ValueType.Float && actual.NonNullable == ValueType.Int)
        {
            return actual.IsNullable
                ? $"(& {{ param($v) if ($null -eq $v) {{ return $null }}; return [double]$v }} ({value}))"
                : $"([double]({value}))";
        }
        return value;
    }

    private static string Clone(string value, ValueType type) => type.IsComposite
        ? $"(& $script:__rukbat_clone ({value}) $script:__rukbat_clone)"
        : value;

    private string Location(Node node)
    {
        var line = module.Source.Text[..node.Token.Offset].Count(character => character == '\n') + 1;
        return Quote(SourceName(module) + ":" + line);
    }

    private string IndexAddress(Index index)
    {
        // Evaluate a potentially side-effecting index only once and retain its target in a temporary.
        var slot = "$__rukbat_slot" + temporaryId++;
        Line($"{slot} = & $script:__rukbat_index ({RawExpr(index.Receiver)}) ({Expr(index.Offset)}) {Location(index)} $true $script:__rukbat_raise");
        return $"{slot}.array[{slot}.offset]";
    }

    private string Address(Expression expression) => expression switch
    {
        Name name => checker.Variables[name].PowerShellName,
        Member member => $"{Address(member.Receiver)}[{Quote(checker.Fields[member].Key)}]",
        Index index => IndexAddress(index),
        _ => throw new InvalidOperationException("Invalid field assignment target.")
    };

    private string RawExpr(Expression expression) => expression switch
    {
        Literal literal => literal.Value switch
        {
            string value => Quote(value),
            bool value => value ? "$true" : "$false",
            int value => value.ToString(CultureInfo.InvariantCulture),
            double value => $"([double]{value.ToString("R", CultureInfo.InvariantCulture)})",
            NullValue => "$null",
            _ => throw new InvalidOperationException()
        },
        ArrayLiteral array => $"(& $script:__rukbat_array @({string.Join("; ", array.Items.Select(item => ",(" + Expr(item) + ")"))}))",
        Index index => $"(& $script:__rukbat_index ({RawExpr(index.Receiver)}) ({Expr(index.Offset)}) {Location(index)} $false $script:__rukbat_raise)",
        Name name => checker.Variables[name].PowerShellName,
        Member member when checker.Types[member.Receiver].Element is not null => $"(({RawExpr(member.Receiver)}).Count)",
        Member member => $"(({RawExpr(member.Receiver)})[{Quote(checker.Fields[member].Key)}])",
        Unary unary => unary.Token.Text == "!"
            ? $"(-not {Expr(unary.Value)})"
            : checker.Types[unary] == ValueType.Float
                ? $"([double]({unary.Token.Text}{Expr(unary.Value)}))"
                : $"([int]({unary.Token.Text}{Expr(unary.Value)}))",
        Binary binary => Binary(binary),
        Call call => Call(call),
        _ => throw new InvalidOperationException("Unbound expression.")
    };

    private string Binary(Binary binary)
    {
        if (binary.Token.Text is "==" or "!=" &&
            (binary.Left is Literal { Value: NullValue } || binary.Right is Literal { Value: NullValue }))
        {
            var value = binary.Left is Literal { Value: NullValue } ? binary.Right : binary.Left;
            var nullOperator = binary.Token.Text == "==" ? "-ceq" : "-cne";
            // PowerShell filters when an array is on the left of -eq/-ne. Keep null on the left
            // so nullable array comparison always produces one boolean, including for [].
            return $"($null {nullOperator} {Expr(value)})";
        }

        var op = binary.Token.Text switch
        {
            "==" => "-ceq",
            "!=" => "-cne",
            "<" => "-lt",
            "<=" => "-le",
            ">" => "-gt",
            ">=" => "-ge",
            "&&" => "-and",
            "||" => "-or",
            _ => binary.Token.Text
        };
        var expression = $"({Expr(binary.Left)} {op} {Expr(binary.Right)})";
        if (checker.Types[binary] == ValueType.Int)
        {
            return op == "/" ? $"([int][Math]::Truncate({expression}))" : $"([int]{expression})";
        }
        if (checker.Types[binary] == ValueType.Float)
        {
            return $"(& $script:__rukbat_float ([double]({expression})) {Location(binary)} $script:__rukbat_raise)";
        }

        return expression;
    }

    private string Call(Call call)
    {
        if (checker.ArrayAppends.Contains(call))
        {
            var address = Address(call.Receiver!);
            if (call.Arguments.Count != 1)
            {
                return "$null";
            }
            var value = Expr(call.Arguments[0].Value);
            return $"({address} = (& $script:__rukbat_append ({address}) ({value})))";
        }
        if (checker.StandardCalls.TryGetValue(call, out var standardCall))
        {
            if (standardCall == "json.decode")
            {
                return $"(& $script:__rukbat_json_decode ({Expr(call.Arguments[0].Value)}) {Schema(checker.Types[call])})";
            }
            if (standardCall == "json.encode")
            {
                return $"(& $script:__rukbat_json_encode ({Expr(call.Arguments[0].Value)}) {Schema(checker.Types[call.Arguments[0].Value])})";
            }
            var standardArguments = string.Join("; ", call.Arguments.Select(argument => ",(" + Expr(argument.Value) + ")"));
            var invocation = $"(& $script:__rukbat_standard {Quote(standardCall)} @({standardArguments}))";
            if (standardCall == "process.run")
            {
                var fields = checker.Types[call].Struct!.Fields;
                return $"(& {{ $result = {invocation}; return @{{" +
                    $"{Quote(fields["exit_code"].Key)} = [int]$result[0]; " +
                    $"{Quote(fields["stdout"].Key)} = [string]$result[1]; " +
                    $"{Quote(fields["stderr"].Key)} = [string]$result[2]" + "}})";
            }
            if (checker.Types[call].Element is not null)
            {
                return $"(& $script:__rukbat_array ({invocation}))";
            }
            return invocation;
        }
        if (checker.Constructions.ContainsKey(call))
        {
            var fields = call.Arguments.Select(argument =>
                $"{Quote(checker.ConstructionFields[argument].Key)} = {Expr(argument.Value)}");
            return $"@{{{string.Join("; ", fields)}}}";
        }

        if (call.PowerShellType is not null)
        {
            return PowerShellCall(call);
        }
        if (call.Receiver is null && call.Name == "args")
        {
            return "$script:__rukbat_arguments";
        }
        if (call.Receiver is null && call.Name is "print" or "eprint")
        {
            var stream = call.Name == "eprint" ? "Error" : "Out";
            return $"([Console]::{stream}.WriteLine([object]({Expr(call.Arguments[0].Value)})))";
        }
        if (call.Receiver is null && call.Name == "exit")
        {
            // Process termination crosses module/function boundaries and cannot be caught as Error.
            return $"(& {{ param([int]$code) if ($code -lt 0) {{ throw 'exit code must be non-negative.' }}; [Console]::Out.Flush(); [Console]::Error.Flush(); [Environment]::Exit($code) }} ({Expr(call.Arguments[0].Value)}))";
        }

        var function = checker.Calls[call];
        var arguments = call.Arguments.Select(a => Expr(a.Value));
        // Only the method receiver is borrowed for mutation. Ordinary arguments remain value copies.
        if (function.Owner is not null)
        {
            arguments = arguments.Prepend(RawExpr(call.Receiver!));
        }

        var values = arguments.ToArray();
        if (function.Module == module)
        {
            return $"({function.PowerShellName}{string.Concat(values.Select(a => " (" + a + ")"))})";
        }

        var receiver = $"$script:__rukbat_dependencies[{Quote(function.Module.Id)}]";
        return $"({receiver}.{function.PowerShellName}({string.Join(", ", values)}))";
    }

    private string PowerShellCall(Call call)
    {
        // The first argument is the command. Split the rest into positional and named splats.
        var positional = string.Join("; ", call.Arguments
            .Skip(1)
            .Where(argument => argument.Name is null)
            .Select(argument => ",(" + PowerShellArgument(argument.Value) + ")"));
        var named = string.Join("; ", call.Arguments
            .Skip(1)
            .Where(argument => argument.Name is not null)
            .Select(argument => $"{Quote(argument.Name!)} = {PowerShellArgument(argument.Value)}"));

        return $"(& $script:__rukbat_runtime {Schema(checker.Types[call])} " +
            $"({Expr(call.Arguments[0].Value)}) @({positional}) @{{{named}}} {Location(call)} $script:__rukbat_error $script:__rukbat_raise)";
    }

    private string PowerShellArgument(Expression expression)
    {
        var value = Expr(expression);
        return checker.Types[expression].NonNullable.Element is null
            ? value
            : $"(& {{ param($value) if ($null -eq $value) {{ return $null }}; return ,([object[]]$value) }} ({value}))";
    }
}
