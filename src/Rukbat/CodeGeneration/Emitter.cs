using System.Text;

namespace Rukbat;

internal sealed partial class Emitter(TypeChecker checker, DebugMap? debugMap = null)
{
    private const int IndentationWidth = 4;
    private const int RuntimeFailureExitCode = 1;

    private readonly StringBuilder output = new();
    private Module module = null!;
    private string? sourceDirectory;
    private string SourceName(Module current) => sourceDirectory is null || !Path.IsPathFullyQualified(current.Source.Path)
        ? current.Source.Path
        : Path.GetRelativePath(sourceDirectory, current.Source.Path).Replace('\\', '/');
    private int indentation;
    private int temporaryId;
    private int generatedLine = 1;
    private ValueType currentReturnType = ValueType.Void;
    private string? returnLabel;
    private string? returnValue;
    private static string Quote(string value) => "'" + value.Replace("'", "''") + "'";
    private static string TypeName(ValueType type)
    {
        if (type.IsNullable)
        {
            return "object";
        }
        if (type.Element is not null)
        {
            return "System.Collections.Generic.List[object]";
        }
        if (type.DictionaryKey is not null) return "hashtable";

        if (type == ValueType.Int) return "long";
        if (type == ValueType.Float)
        {
            return "double";
        }
        if (type.IsJsonValue) return "RukbatJsonValue";
        if (type.IsCsvRow) return "RukbatCsvRow";
        if (type.IsCliResult) return "object";
        if (type == ValueType.FileLines) return "object";
        if (type == ValueType.Encoding || type == HashValues.Algorithm) return "string";
        if (type == HttpValues.Method) return "string";
        if (type == HttpValues.Body) return "RukbatHttpBody";
        if (DateTimeValues.Contains(type)) return DateTimeValues.RuntimeName(type);
        return type.Struct is null ? type.Name : "hashtable";
    }

    private void Line(string text)
    {
        output.Append(' ', indentation * IndentationWidth).AppendLine(text);
        if (debugMap is not null) generatedLine += text.Count(character => character == '\n') + 1;
    }
    private void RawLine(string text)
    {
        output.AppendLine(text);
        if (debugMap is not null) generatedLine += text.Count(character => character == '\n') + 1;
    }

    public string Emit(List<Module> modules, TestInvocation? test = null)
    {
        sourceDirectory = Path.IsPathFullyQualified(modules[^1].Source.Path)
            ? Path.GetDirectoryName(modules[^1].Source.Path) : null;
        Line("# Generated by Rukbat. Compatible with Windows PowerShell 5.1.");
        Line("if ($ExecutionContext.SessionState.LanguageMode -ne 'FullLanguage') {");
        Line("    Write-Error 'Rukbat requires FullLanguage mode; no program operations were started.'");
        Line(debugMap is null ? $"    exit {RuntimeFailureExitCode}" : $"    [Environment]::Exit({RuntimeFailureExitCode})");
        Line("}");
        Line("& {");
        indentation++;
        Line("param([string[]]$__rukbat_arguments, [bool]$__rukbat_direct_file, [string]$__rukbat_script_dir)");
        Line("$ErrorActionPreference = 'Stop'");
        Line("[Console]::OutputEncoding = [System.Text.Encoding]::UTF8");
        Line("Set-StrictMode -Version Latest");
        EmitLines(RuntimeResources.ReadPowerShell("EntryContextRuntime"));
        Line("$__rukbat_modules = @{}");
        if (debugMap is not null)
            Line("$global:__rukbat_debug_frames = New-Object 'System.Collections.Generic.List[object]'");
        EmitErrorRuntime();
        EmitRuntime();
        if (checker.Types.Any(pair => pair.Key is Rukbat.Binary or Unary && pair.Value == ValueType.Int) ||
            modules.Any(current => current.StandardName == "math"))
        {
            EmitNativeLoader("Numbers");
            Line("& $__rukbat_load_Numbers");
        }
        Line("$__rukbat_arguments = & $__rukbat_array $__rukbat_arguments");
        Line("$__rukbat_json_decode = $null");
        Line("$__rukbat_json_encode = $null");
        Line("$__rukbat_standard = $null");
        if (modules.Any(current => current.StandardName == "json"))
        {
            EmitJsonRuntime();
        }
        var standardModules = modules
            .Where(current => current.StandardName is "fs" or "path" or "csv" or "json" or "env" or "process" or "text" or "encoding" or "math" or "datetime" or "array" or "zip" or "hash" or "http" or "cli")
            .Select(current => current.StandardName!)
            .ToHashSet(StringComparer.Ordinal);
        if (standardModules.Count != 0)
        {
            EmitStandardRuntime(standardModules);
        }
        Line("try {");
        indentation++;
        foreach (var current in modules)
        {
            EmitModule(current);
        }
        if (test is not null)
        {
            var symbol = test.Function;
            var argument = "";
            if (symbol.Function.Parameters.Count != 0)
            {
                var fields = checker.Variables[symbol.Function.Parameters[0]].Type.Struct!.Fields;
                argument = $"@{{{Quote(fields["temp_dir"].Key)} = {Quote(test.WorkingDirectory)}; " +
                    $"{Quote(fields["source_dir"].Key)} = {Quote(Path.GetDirectoryName(symbol.Module.Source.Path)!)}" + "}";
            }
            Line($"$null = $__rukbat_modules[{Quote(symbol.Module.Id)}].{symbol.PowerShellName}({argument})");
            Line($"[IO.File]::WriteAllText({Quote(test.CompletionPath)}, 'completed')");
        }
        indentation--;
        Line("} catch {");
        indentation++;
        Line($"$__rukbat_failure = & $__rukbat_error $_ {Quote(SourceName(modules[^1]) + ":1")}");
        Line("[Console]::Error.WriteLine(('{0}: error: {1}' -f $__rukbat_failure.__rukbat_location, $__rukbat_failure.message))");
        Line(debugMap is null ? $"exit {RuntimeFailureExitCode}" : $"[Environment]::Exit({RuntimeFailureExitCode})");
        indentation--;
        Line("}");
        indentation--;
        Line("} ([string[]]$args) ($MyInvocation.ScriptLineNumber -eq 0) $PSScriptRoot");
        return output.ToString();
    }

    private void EmitModule(Module current)
    {
        module = current;
        Line($"$__rukbat_modules[{Quote(current.Id)}] = New-Module -AsCustomObject " +
            "-ArgumentList $__rukbat_modules, $__rukbat_runtime, $__rukbat_array, $__rukbat_clone, $__rukbat_append, $__rukbat_index, $__rukbat_float, $__rukbat_json_decode, $__rukbat_json_encode, $__rukbat_standard, $__rukbat_error, $__rukbat_raise, $__rukbat_arguments, $__rukbat_dictionary -ScriptBlock {");
        indentation++;
        Line("param($__rukbat_dependencies, $__rukbat_runtime, $__rukbat_array, $__rukbat_clone, $__rukbat_append, $__rukbat_index, $__rukbat_float, $__rukbat_json_decode, $__rukbat_json_encode, $__rukbat_standard, $__rukbat_error, $__rukbat_raise, [System.Collections.Generic.List[object]]$__rukbat_arguments, $__rukbat_dictionary)");
        Line("Set-StrictMode -Version Latest");
        Line("$ErrorActionPreference = 'Stop'");

        // Define functions before top-level execution so calls do not depend on declaration order.
        var functions = checker.Functions.Values.Where(function => function.Module == current).ToArray();
        foreach (var function in functions)
        {
            EmitFunction(function.Function);
        }

        var statements = current.Statements
            .Where(statement => statement is not Function and not StructDeclaration)
            .ToList();
        DebugEnter(Path.GetFileName(current.Source.Path), []);
        EmitGuardedStatements(statements, Quote(SourceName(current) + ":1"));
        DebugLeave();

        var exports = functions.Select(function => Quote(function.PowerShellName));
        Line($"Export-ModuleMember -Function @({string.Join(", ", exports)})");
        indentation--;
        Line("}");
    }

    private void EmitFunction(Function function)
    {
        Line($"function {checker.Functions[function].PowerShellName} {{");
        indentation++;
        var parameters = function.Parameters.Select(parameter =>
            $"[{TypeName(checker.Variables[parameter].Type)}]{checker.Variables[parameter].PowerShellName}");
        if (checker.Functions[function].Owner is not null)
        {
            parameters = parameters.Prepend("[hashtable]$__rukbat_self");
        }

        Line($"param({string.Join(", ", parameters)})");
        var previousReturnType = currentReturnType;
        currentReturnType = checker.Functions[function].ReturnType;
        var globals = module.Statements.OfType<Variable>().Select(variable => checker.Variables[variable]);
        var parametersForDebug = function.Parameters.Select(parameter => checker.Variables[parameter]);
        if (checker.Functions[function].Owner is { } owner)
            parametersForDebug = parametersForDebug.Prepend(new("self", owner.BoundType, "$__rukbat_self"));
        DebugEnter(checker.Functions[function].Owner is { } debugOwner
            ? debugOwner.Declaration.Token.Text + "." + function.Name : function.Name, parametersForDebug.Concat(globals));
        if (ContainsOwnedIteration(function.Body))
        {
            returnLabel = "__rukbat_function_exit" + temporaryId++;
            returnValue = "$__rukbat_function_result" + temporaryId++;
            Line($"{returnValue} = $null");
            Line($":{returnLabel} do {{");
            indentation++;
            EmitGuardedStatements(function.Body, Location(function));
            indentation--;
            Line("} while ($false)");
            EmitReturnValue(returnValue);
            returnLabel = null;
            returnValue = null;
        }
        else EmitGuardedStatements(function.Body, Location(function));
        DebugLeave();
        currentReturnType = previousReturnType;
        indentation--;
        Line("}");
    }
}
